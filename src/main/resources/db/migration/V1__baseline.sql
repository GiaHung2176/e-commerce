-- V1: baseline schema (PostgreSQL), khớp với các entity tại thời điểm hoàn thành Block C.

CREATE TABLE categories (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(255) NOT NULL,
    description VARCHAR(255),
    PRIMARY KEY (id),
    CONSTRAINT uk_categories_name UNIQUE (name)
);

CREATE TABLE users (
    id       BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    username VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(20)  NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'CUSTOMER'))
);

CREATE TABLE tags (
    id   BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_tags_name UNIQUE (name)
);

CREATE TABLE products (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    name           VARCHAR(255)   NOT NULL,
    price          NUMERIC(38, 2) NOT NULL,
    stock_quantity INT,
    category_id    BIGINT,
    version        BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE TABLE product_tags (
    product_id BIGINT NOT NULL,
    tag_id     BIGINT NOT NULL,
    PRIMARY KEY (product_id, tag_id),
    CONSTRAINT fk_product_tags_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_product_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (id)
);

CREATE TABLE profiles (
    id        BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR(255) NOT NULL,
    phone     VARCHAR(255),
    address   VARCHAR(255),
    user_id   BIGINT       NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE orders (
    id         BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    order_date TIMESTAMP(6),
    status     VARCHAR(20),
    user_id    BIGINT,
    PRIMARY KEY (id),
    CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE order_items (
    id             BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    quantity       INT            NOT NULL,
    price_at_order NUMERIC(38, 2) NOT NULL,
    order_id       BIGINT         NOT NULL,
    product_id     BIGINT         NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_items_product FOREIGN KEY (product_id) REFERENCES products (id)
);
